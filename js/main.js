/**
 * ปุ่มเริ่มทำแบบสำรวจใหม่
 */
function handleSurveyRestart() {
  surveyState.currentStep = 'category';
  surveyState.selectedCategory = null;
  surveyState.currentQuestionIndex = 0;
  surveyState.answers = [];
  surveyState.activeBranch = 'pressure';
  surveyState.isTyping = false;

  showSurveyView('category');

  const surveyContainer = document.getElementById('survey');
  if (surveyContainer) {
    surveyContainer.scrollIntoView({ behavior: 'smooth', block: 'start' });
  }
}

/**
 * ฟังก์ชันช่วยสลับ View ระหว่าง Category, Question และ Summary
 */
function showSurveyView(viewName) {
  const catView = document.getElementById('surveyCategoryView');
  const qView = document.getElementById('surveyQuestionView');
  const sumView = document.getElementById('surveySummaryView');

  if (catView) catView.style.display = (viewName === 'category') ? 'block' : 'none';
  if (qView) qView.style.display = (viewName === 'question') ? 'block' : 'none';
  if (sumView) sumView.style.display = (viewName === 'summary') ? 'block' : 'none';
}
