/* ===================================================================
   State Management for Survey (การจัดการสถานะบทสนทนา)
   =================================================================== */
let surveyState = {
  currentStep: 'category', // 'category' | 'question' | 'summary'
  selectedCategory: null,
  currentQuestionIndex: 0, // 0 to 4 (รวม 5 คำถาม)
  answers: [], // เก็บ { questionIndex, questionText, optionIndex, selectedOptionText, branchOrTag, responseText }
  activeBranch: 'pressure',
  isTyping: false
};

/**
 * กำหนดค่าและผูก Event Listener ให้ระบบแบบสอบถามเชิงสนทนา
 */
function initSurveySystem() {
  const categoryCards = document.querySelectorAll('.survey-category-card');
  const directStartBtn = document.getElementById('startSurveyDirectBtn');
  const prevBtn = document.getElementById('surveyPrevBtn');
  const nextBtn = document.getElementById('surveyNextBtn');
  const restartBtn = document.getElementById('surveyRestartBtn');
  const quickRestartBtn = document.getElementById('surveyQuickRestartBtn');

  // 1. ผูก Event เลือกลำดับหมวดหมู่จาก View 1
  if (categoryCards.length) {
    categoryCards.forEach(card => {
      card.addEventListener('click', () => {
        const catId = card.getAttribute('data-category');
        selectSurveyCategory(catId);
      });

      card.addEventListener('keydown', (e) => {
        if (e.key === 'Enter' || e.key === ' ') {
          e.preventDefault();
          card.click();
        }
      });
    });
  }

  // 1.1 ปุ่มเริ่มการสนทนาโดยตรงจากหน้าหมวดหมู่
  if (directStartBtn) {
    directStartBtn.addEventListener('click', () => {
      startDirectSurvey();
    });
  }

  // 2. ปุ่มย้อนกลับ
  if (prevBtn) {
    prevBtn.addEventListener('click', handleSurveyPrev);
  }

  // 3. ปุ่มดำเนินการต่อ
  if (nextBtn) {
    nextBtn.addEventListener('click', handleSurveyNext);
  }

  // 4. ปุ่มเริ่มทำแบบสำรวจใหม่
  if (restartBtn) {
    restartBtn.addEventListener('click', handleSurveyRestart);
  }
  if (quickRestartBtn) {
    quickRestartBtn.addEventListener('click', handleSurveyRestart);
  }
}

/**
 * เริ่มต้นเมื่อผู้ใช้เลือกการ์ดหมวดปัญหาจาก View 1
 * ระบบจะสลับไปหน้าคำถามที่ 1 โดยเลือกหมวดนั้นไว้ให้ทันที
 * พร้อมแสดงการพิมพ์และข้อความตอบกลับสะท้อนใจอย่างอบอุ่น
 */
function selectSurveyCategory(catId) {
  const cat = surveyCategories[catId] || surveyCategories.academics;
  surveyState.selectedCategory = cat;
  surveyState.currentStep = 'question';
  surveyState.currentQuestionIndex = 0;
  surveyState.answers = [];
  surveyState.activeBranch = cat.defaultBranch || 'pressure';

  // หา option ใน q0 ที่ตรงกับหมวดที่เลือก
  const q0Data = conversationalQuestions.q0;
  const optIdx = q0Data.options.findIndex(opt => opt.catId === catId);
  const matchedOpt = optIdx !== -1 ? q0Data.options[optIdx] : q0Data.options[0];

  // บันทึกคำตอบข้อแรกไว้
  surveyState.answers[0] = {
    questionIndex: 0,
    questionText: q0Data.question,
    optionIndex: optIdx !== -1 ? optIdx : 0,
    selectedOptionText: matchedOpt.text,
    branchOrTag: catId,
    responseText: matchedOpt.response
  };

  showSurveyView('question');
  renderCurrentQuestion();

  // แสดง Typing Animation สั้น ๆ แล้วแสดงข้อความตอบกลับ
  triggerConversationalResponse(matchedOpt.response);

  // เลื่อนหน้าจอมายังกรอบคำถาม
  const surveyContainer = document.getElementById('survey');
  if (surveyContainer) {
    surveyContainer.scrollIntoView({ behavior: 'smooth', block: 'start' });
  }
}

/**
 * เริ่มต้นคำถามแรกโดยไม่ได้เลือกหมวดหมู่ล่วงหน้า ให้ผู้ใช้เลือกใน Chat ได้เอง
 */
function startDirectSurvey() {
  surveyState.selectedCategory = null;
  surveyState.currentStep = 'question';
  surveyState.currentQuestionIndex = 0;
  surveyState.answers = [];
  surveyState.activeBranch = 'pressure';

  showSurveyView('question');
  renderCurrentQuestion();

  const surveyContainer = document.getElementById('survey');
  if (surveyContainer) {
    surveyContainer.scrollIntoView({ behavior: 'smooth', block: 'start' });
  }
}

/**
 * ดึงข้อมูลคำถามตามลำดับปัจจุบันและ Branch ที่เกี่ยวข้อง
 */
function getQuestionDataForIndex(qIndex) {
  if (qIndex === 0) {
    return conversationalQuestions.q0;
  }

  const catId = surveyState.selectedCategory ? surveyState.selectedCategory.id : 'academics';

  if (qIndex === 1) {
    return conversationalQuestions.q1_branches[catId] || conversationalQuestions.q1_branches.academics;
  }

  if (qIndex === 2) {
    const branchKey = surveyState.activeBranch || 'default_branch';
    return conversationalQuestions.q2_branches[branchKey] || 
           conversationalQuestions.q2_branches.default_branch;
  }

  if (qIndex === 3) {
    return conversationalQuestions.q3;
  }

  if (qIndex === 4) {
    return conversationalQuestions.q4;
  }

  return conversationalQuestions.q0;
}

/**
 * แสดงคำถามปัจจุบันพร้อมตัวเลือก และกู้คืนสถานะหากเคยตอบไว้แล้ว
 */
function renderCurrentQuestion() {
  const qIndex = surveyState.currentQuestionIndex;
  const qData = getQuestionDataForIndex(qIndex);
  if (!qData) return;

  const totalQuestions = 5;
  const currentNum = qIndex + 1;
  const percent = Math.round((currentNum / totalQuestions) * 100);

  // อัปเดตส่วนหัวและ Progress Bar
  const categoryBadge = document.getElementById('surveyCategoryBadge');
  const counterText = document.getElementById('surveyCounterText');
  const progressBar = document.getElementById('surveyProgressBar');
  const questionTitle = document.getElementById('surveyQuestionTitle');
  const questionHint = document.getElementById('surveyQuestionHint');
  const optionsContainer = document.getElementById('surveyOptionsContainer');
  const nextBtn = document.getElementById('surveyNextBtn');
  const typingIndicator = document.getElementById('surveyTypingIndicator');
  const responseSection = document.getElementById('surveyResponseSection');
  const responseText = document.getElementById('surveyResponseText');

  if (categoryBadge) {
    if (surveyState.selectedCategory) {
      categoryBadge.innerHTML = `<i class="bi ${surveyState.selectedCategory.icon} me-1"></i>หมวด: ${surveyState.selectedCategory.title}`;
    } else {
      categoryBadge.innerHTML = `<i class="bi bi-chat-dots me-1"></i>หมวด: สำรวจใจตัวเอง`;
    }
  }

  if (counterText) {
    counterText.textContent = `คำถามที่ ${currentNum} จาก ${totalQuestions}`;
  }
  if (progressBar) {
    progressBar.style.width = `${percent}%`;
    progressBar.setAttribute('aria-valuenow', percent);
  }
  if (questionTitle) {
    questionTitle.textContent = qData.question;
  }
  if (questionHint) {
    questionHint.textContent = qData.hint || '';
  }

  // ซ่อน typing indicator เป็นค่าเริ่มต้น
  if (typingIndicator) {
    typingIndicator.style.display = 'none';
  }

  // ตรวจสอบว่าเคยตอบข้อนี้ไว้แล้วหรือไม่
  const existingAnswer = surveyState.answers[qIndex];

  // อัปเดตข้อความปุ่มถัดไป
  if (nextBtn) {
    if (qIndex === totalQuestions - 1) {
      nextBtn.innerHTML = `<span>ดูผลสรุปความรู้สึก</span><i class="bi bi-stars ms-1"></i>`;
    } else {
      nextBtn.innerHTML = `<span>ดำเนินการต่อ</span><i class="bi bi-arrow-right ms-1"></i>`;
    }

    if (existingAnswer) {
      nextBtn.disabled = false;
      nextBtn.classList.add('btn-pulse');
    } else {
      nextBtn.disabled = true;
      nextBtn.classList.remove('btn-pulse');
    }
  }

  // หากเคยมีคำตอบ ให้แสดงข้อความตอบกลับเดิมทันที
  if (existingAnswer && responseSection && responseText) {
    responseText.textContent = existingAnswer.responseText;
    responseSection.style.display = 'block';
  } else if (responseSection) {
    responseSection.style.display = 'none';
  }

  // สร้าง Option Cards
  if (optionsContainer) {
    optionsContainer.innerHTML = '';

    qData.options.forEach((opt, idx) => {
      const optionCard = document.createElement('div');
      optionCard.className = 'survey-option-card';
      optionCard.setAttribute('tabindex', '0');
      optionCard.setAttribute('role', 'radio');
      optionCard.setAttribute('aria-checked', 'false');

      const isSelected = existingAnswer && existingAnswer.optionIndex === idx;
      if (isSelected) {
        optionCard.classList.add('selected');
        optionCard.setAttribute('aria-checked', 'true');
      } else if (existingAnswer) {
        optionCard.classList.add('dimmed');
      }

      optionCard.innerHTML = `
        <div class="option-indicator">
          <i class="bi ${isSelected ? 'bi-check-circle-fill' : 'bi-circle'}"></i>
        </div>
        <div class="option-text">${opt.text}</div>
      `;

      // Event คลิกเลือกคำตอบ
      optionCard.addEventListener('click', () => {
        selectSurveyOption(qIndex, qData.question, opt, idx);
      });

      optionCard.addEventListener('keydown', (e) => {
        if (e.key === 'Enter' || e.key === ' ') {
          e.preventDefault();
          optionCard.click();
        }
      });

      optionsContainer.appendChild(optionCard);
    });
  }
}

/**
 * จัดการเมื่อผู้ใช้เลือกคำตอบในข้อปัจจุบัน
 * ปฏิบัติตามลำดับขั้นตอน:
 * 1. ผู้ใช้เลือกคำตอบ
 * 2. ปรับไฮไลต์ตัวเลือกที่เลือก และลดความเด่นตัวเลือกอื่น
 * 3. แสดง Typing Animation ชั่วขณะ
 * 4. แสดงข้อความตอบกลับจาก Safe Haven
 * 5. เปิดใช้งานปุ่ม 'ดำเนินการต่อ'
 */
function selectSurveyOption(qIndex, questionText, optionObj, optionIndex) {
  if (surveyState.isTyping) return;

  // บันทึกคำตอบ
  surveyState.answers[qIndex] = {
    questionIndex: qIndex,
    questionText: questionText,
    optionIndex: optionIndex,
    selectedOptionText: optionObj.text,
    branchOrTag: optionObj.branch || optionObj.tag || optionObj.catId || '',
    responseText: optionObj.response
  };

  // หากเป็นข้อที่ 0 (เลือกหมวด)
  if (qIndex === 0) {
    const catId = optionObj.catId || 'academics';
    const cat = surveyCategories[catId];
    if (cat) {
      surveyState.selectedCategory = cat;
      const categoryBadge = document.getElementById('surveyCategoryBadge');
      if (categoryBadge) {
        categoryBadge.innerHTML = `<i class="bi ${cat.icon} me-1"></i>หมวด: ${cat.title}`;
      }
    }
    // รีเซ็ตคำตอบถัดไปเพื่อป้องกัน Branch ขัดแย้ง
    surveyState.answers.splice(1);
    surveyState.activeBranch = (cat && cat.defaultBranch) ? cat.defaultBranch : 'pressure';
  }

  // หากเป็นข้อที่ 1 และมี branch
  if (qIndex === 1 && optionObj.branch) {
    surveyState.activeBranch = optionObj.branch;
    // รีเซ็ตข้อที่ 3, 4, 5
    surveyState.answers.splice(2);
  }

  // อัปเดต UI ตัวเลือก
  const optionCards = document.querySelectorAll('.survey-option-card');
  optionCards.forEach((card, idx) => {
    const isSelected = (idx === optionIndex);
    card.classList.toggle('selected', isSelected);
    card.classList.toggle('dimmed', !isSelected);
    card.setAttribute('aria-checked', isSelected ? 'true' : 'false');
    const indicatorIcon = card.querySelector('.option-indicator i');
    if (indicatorIcon) {
      indicatorIcon.className = `bi ${isSelected ? 'bi-check-circle-fill' : 'bi-circle'}`;
    }
  });

  // แสดง Typing Animation แล้วเปิดข้อความตอบกลับ
  triggerConversationalResponse(optionObj.response);
}

/**
 * แอนิเมชันพิมพ์ข้อความและเปิดเผยข้อความตอบกลับ
 */
function triggerConversationalResponse(responseText) {
  const typingIndicator = document.getElementById('surveyTypingIndicator');
  const responseSection = document.getElementById('surveyResponseSection');
  const responseTextEl = document.getElementById('surveyResponseText');
  const nextBtn = document.getElementById('surveyNextBtn');

  // ซ่อนข้อความเดิมชั่วคราวและปิดปุ่มดำเนินการต่อระหว่างคิด
  if (responseSection) responseSection.style.display = 'none';
  if (nextBtn) {
    nextBtn.disabled = true;
    nextBtn.classList.remove('btn-pulse');
  }

  if (typingIndicator) {
    typingIndicator.style.display = 'flex';
  }
  surveyState.isTyping = true;

  // จำลองจังหวะที่ Safe Haven รับฟังและเรียบเรียงความคิด (450ms)
  setTimeout(() => {
    if (typingIndicator) typingIndicator.style.display = 'none';
    surveyState.isTyping = false;

    if (responseTextEl) {
      responseTextEl.textContent = responseText;
    }
    if (responseSection) {
      responseSection.style.display = 'block';
      // เลื่อนหน้าจอให้เห็นข้อความตอบกลับอย่างชัดเจน
      responseSection.scrollIntoView({ behavior: 'smooth', block: 'nearest' });
    }

    // เปิดใช้งานปุ่ม 'ดำเนินการต่อ' พร้อมเอฟเฟกต์นำสายตา
    if (nextBtn) {
      nextBtn.disabled = false;
      nextBtn.classList.add('btn-pulse');
    }
  }, 450);
}

/**
 * ปุ่มย้อนกลับ (Back Button)
 * สามารถย้อนกลับไปแก้ไขคำตอบเดิมได้ และเมื่อย้อนกลับจะคงคำตอบเดิมไว้
 */
function handleSurveyPrev() {
  if (surveyState.isTyping) return;

  if (surveyState.currentQuestionIndex > 0) {
    surveyState.currentQuestionIndex--;
    renderCurrentQuestion();
    const surveyContainer = document.getElementById('survey');
    if (surveyContainer) {
      surveyContainer.scrollIntoView({ behavior: 'smooth', block: 'start' });
    }
  } else {
    // หากอยู่ที่ข้อ 1 แล้วกดย้อนกลับ ให้กลับไปเลือกหมวดหมู่
    showSurveyView('category');
    const surveyContainer = document.getElementById('survey');
    if (surveyContainer) {
      surveyContainer.scrollIntoView({ behavior: 'smooth', block: 'start' });
    }
  }
}

/**
 * ปุ่มดำเนินการต่อ (Continue / Next Button)
 * ไม่ข้ามขั้นตอนการตอบกลับ ผู้ใช้ต้องเลือกคำตอบและอ่านข้อความก่อน
 */
function handleSurveyNext() {
  if (surveyState.isTyping) return;

  const qIndex = surveyState.currentQuestionIndex;
  if (!surveyState.answers[qIndex]) return;

  if (qIndex < 4) {
    surveyState.currentQuestionIndex++;
    renderCurrentQuestion();

    const surveyContainer = document.getElementById('survey');
    if (surveyContainer) {
      surveyContainer.scrollIntoView({ behavior: 'smooth', block: 'start' });
    }
  } else {
    // ตอบครบ 5 ข้อแล้ว เข้าสู่หน้าสรุปผล
    surveyState.currentStep = 'summary';
    renderSurveySummary();
    showSurveyView('summary');

    const surveyContainer = document.getElementById('survey');
    if (surveyContainer) {
      surveyContainer.scrollIntoView({ behavior: 'smooth', block: 'start' });
    }
  }
}

