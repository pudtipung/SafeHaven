function initMoodCardInteractions() {
  const cards = document.querySelectorAll('.mood-card');
  const responseBox = document.getElementById('moodResponseBox');
  const responseIcon = document.getElementById('responseMoodIcon');
  const responseTitle = document.getElementById('responseMoodTitle');
  const responseBadge = document.getElementById('responseMoodBadge');
  const responseText = document.getElementById('responseMoodText');
  const responseTip = document.getElementById('responseMoodTip');
  const closeBtn = document.getElementById('closeMoodResponse');

  if (!cards.length || !responseBox) return;

  cards.forEach(card => {
    card.addEventListener('click', () => {
      const moodKey = card.getAttribute('data-mood');
      const data = moodData[moodKey];
      if (!data) return;

      cards.forEach(c => c.classList.remove('active'));
      card.classList.add('active');

      if (responseIcon) {
        responseIcon.className = `mood-icon-box ${data.iconClass} mb-0 me-3 flex-shrink-0`;
        responseIcon.innerHTML = `<i class="bi ${data.icon}"></i>`;
      }
      if (responseTitle) responseTitle.textContent = data.title;
      if (responseBadge) responseBadge.textContent = data.badge;
      if (responseText) responseText.textContent = data.message;
      if (responseTip) responseTip.textContent = data.tip;

      responseBox.classList.add('show');
      responseBox.scrollIntoView({ behavior: 'smooth', block: 'nearest' });
    });

    card.addEventListener('keydown', (e) => {
      if (e.key === 'Enter' || e.key === ' ') {
        e.preventDefault();
        card.click();
      }
    });
  });

  if (closeBtn) {
    closeBtn.addEventListener('click', () => {
      responseBox.classList.remove('show');
      cards.forEach(c => c.classList.remove('active'));
    });
  }
}

/* ===================================================================
   3. Back to Top Button
   =================================================================== */
function initBackToTop() {
  const backToTopBtn = document.getElementById('backToTopBtn');
  if (!backToTopBtn) return;

  window.addEventListener('scroll', () => {
    if (window.scrollY > 350) {
      backToTopBtn.classList.add('show');
    } else {
      backToTopBtn.classList.remove('show');
    }
  }, { passive: true });

  backToTopBtn.addEventListener('click', () => {
    window.scrollTo({
      top: 0,
      behavior: 'smooth'
    });
  });
}

/* ===================================================================
   4. Smooth Anchor Scrolling & Mobile Nav collapse
   =================================================================== */
function initSmoothScroll() {
  const navLinks = document.querySelectorAll('.navbar-nav .nav-link, a[href^="#"]');
  const navCollapse = document.getElementById('navbarNav');
  const navToggler = document.querySelector('.navbar-toggler');

  // Fallback toggler handling when Bootstrap JS is unavailable
  if (navToggler && navCollapse) {
    navToggler.addEventListener('click', (e) => {
      if (typeof bootstrap === 'undefined' || !bootstrap.Collapse) {
        e.preventDefault();
        const isOpen = navCollapse.classList.contains('show');
        if (isOpen) {
          navCollapse.classList.remove('show');
          navToggler.classList.add('collapsed');
          navToggler.setAttribute('aria-expanded', 'false');
        } else {
          navCollapse.classList.add('show');
          navToggler.classList.remove('collapsed');
          navToggler.setAttribute('aria-expanded', 'true');
        }
      }
    });
  }

  navLinks.forEach(link => {
    link.addEventListener('click', (e) => {
      const targetId = link.getAttribute('href');
      if (targetId && targetId.startsWith('#') && targetId.length > 1) {
        const targetElement = document.querySelector(targetId);
        if (targetElement) {
          e.preventDefault();
          targetElement.scrollIntoView({ behavior: 'smooth' });
        }
      }

      // Auto close mobile navbar
      if (navCollapse && navCollapse.classList.contains('show')) {
        let closedWithBootstrap = false;
        if (typeof bootstrap !== 'undefined' && bootstrap.Collapse) {
          try {
            const bsCollapse = (typeof bootstrap.Collapse.getOrCreateInstance === 'function')
              ? bootstrap.Collapse.getOrCreateInstance(navCollapse)
              : (bootstrap.Collapse.getInstance(navCollapse) || new bootstrap.Collapse(navCollapse, { toggle: false }));

            if (bsCollapse && typeof bsCollapse.hide === 'function') {
              bsCollapse.hide();
              closedWithBootstrap = true;
            }
          } catch (err) {
            console.warn('Bootstrap Collapse issue:', err);
          }
        }

        if (!closedWithBootstrap) {
          navCollapse.classList.remove('show');
          if (navToggler) {
            navToggler.classList.add('collapsed');
            navToggler.setAttribute('aria-expanded', 'false');
          }
        }
      }
    });
  });
}

